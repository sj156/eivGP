test_that("pruning audits all draws, protects unfinished work, and logs exact removals", {
 root<-tempfile();dir.create(root);on.exit(unlink(root,recursive=TRUE))
 mech<-file.path(root,'mechanism');dir.create(mech)
 old<-options(eivGP.checkpoint_root=file.path(root,'checkpoints'),eivGP.checkpoint_iterations=2L)
 on.exit(options(old),add=TRUE)
 n<-10L;u<-seq(-1,1,length.out=n);X<-matrix(cos(seq_len(n)),ncol=1)
 C<-matrix(as.integer(u>0)+1L,ncol=1);U<-matrix(u,ncol=1);U[3:8,]<-NA_real_
 fit<-suppressWarnings(fit_eivgp(X=X,y=sin(u)+X[,1]/5,C=C,U_obs=U,engine='multivariate',
   ident='none',n_iter=12L,burn=4L,n_chains=2L,parallel=FALSE,seed=278122L))
 disk<-attr(fit,'eivgp_restart_storage')$directory
 folder<-file.path(mech,'rep001-cal20-CUT');dir.create(folder)
 path<-file.path(folder,'conditional-001.rds');saveRDS(mixedgp_pack_artifact(fit),path)
 saveRDS(list(settings=list(seed=77101L)),file.path(mech,'protocol.rds'))
 measurement<-file.path(root,'checkpoints',paste(rep('a',32),collapse=''));dir.create(measurement)
 saveRDS(list(model=list(component='cut-measurement')),file.path(measurement,'identity.rds'))
 saveRDS(list(unfinished=TRUE),file.path(measurement,'chain-01.rds'))
 paths<-file.path(disk,sprintf('chain-%02d.rds',1:2))
 audit<-function(delete=FALSE) {
   a<-tempfile();on.exit(unlink(a,recursive=TRUE))
   suppressMessages(prune_study_checkpoints(root,dry_run=!delete,audit_dir=a))
 }
 before<-list.files(root,recursive=TRUE,all.files=TRUE)
 z<-audit();expect_equal(sum(z$status=='verified'),1L)
 expect_identical(before,list.files(root,recursive=TRUE,all.files=TRUE))
 expect_equal(sum(z$removed_bytes),0)
 bad<-fit;bad$mcmc$samples_by_chain$U[[1]][1]<-999
 saveRDS(mixedgp_pack_artifact(bad),path)
 z<-audit(TRUE);expect_true(all(file.exists(paths)));expect_true(any(grepl('draw_mismatch',z$reason)))
 saveRDS(mixedgp_pack_artifact(fit),path)
 raw<-readRDS(paths[2]);broken<-raw;broken$rng<-NULL;saveRDS(broken,paths[2])
 z<-audit(TRUE);expect_true(all(file.exists(paths)));expect_true(any(grepl('restart_state_mismatch',z$reason)))
 saveRDS(raw,paths[2])
 unlink(paths[2]);z<-audit(TRUE);expect_true(file.exists(paths[1]));expect_true(any(grepl('incomplete_or_extra',z$reason)))
 saveRDS(raw,paths[2])
 dir.create(file.path(disk,'LOCK'));z<-audit(TRUE);expect_true(all(file.exists(paths)));expect_true(any(z$reason=='locked'))
 unlink(file.path(disk,'LOCK'),recursive=TRUE)
 a<-tempfile();on.exit(unlink(a,recursive=TRUE),add=TRUE)
 hash<-unname(tools::md5sum(path));measurement_hash<-tools::md5sum(file.path(measurement,c('identity.rds','chain-01.rds')))
 z<-suppressMessages(prune_study_checkpoints(root,dry_run=FALSE,audit_dir=a))
 expect_equal(sum(z$chains_removed),2L);expect_true(all(!file.exists(paths)))
 expect_identical(unname(tools::md5sum(path)),hash)
 expect_identical(tools::md5sum(names(measurement_hash)),measurement_hash)
 expect_true(file.exists(file.path(disk,'identity.rds')))
 expect_true(file.exists(file.path(disk,'chain-01-timing.csv')))
 expect_false(file.exists(file.path(mech,'RUN.lock')))
 receipt<-readRDS(file.path(a,'receipts',paste0(basename(disk),'.rds')))
 expect_identical(receipt$status,'removed');expect_true(all(receipt$removed));expect_equal(nrow(receipt$files),2L)
 expect_equal(sum(audit(TRUE)$removed_bytes),0)
})
