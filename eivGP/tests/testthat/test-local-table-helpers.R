test_that('row binding preserves schemas, types and missing columns', {
 a<-data.frame(id=1:2,x=c(3,4));b<-data.frame(id=3L,label='third')
 z<-mixedgp_bind_rows(list(a,NULL),b)
 expect_identical(z,data.frame(id=1:3,x=c(3,4,NA),label=c(NA,NA,'third')))
 expect_identical(mixedgp_bind_rows(),data.frame())
 expect_identical(mixedgp_bind_rows(data.frame(id=integer(),label=character()),data.frame(id=1L)),data.frame(id=1L,label=NA_character_))
 expect_identical(mixedgp_bind_rows(data.frame(id=integer(),label=character())),data.frame(id=integer(),label=character()))
 expect_identical(mixedgp_bind_rows(data.frame(x=factor('a')),data.frame(x='b'))$x,c('a','b'))
 expect_identical(levels(mixedgp_bind_rows(data.frame(x=factor('a')),data.frame(x=factor('b')))$x),c('a','b'))
})
test_that('explicit long and wide tables preserve values, ordering and empty schemas', {
 d<-data.frame(id=c(2L,1L),a=c(.2,NA),b=c(.4,.5))
 long<-mixedgp_pivot_longer(d,c('a','b'),'metric','value')
 expect_identical(long,data.frame(id=c(2L,2L,1L,1L),metric=c('a','b','a','b'),value=c(.2,.4,NA,.5)))
 expect_identical(mixedgp_pivot_wider(long,'metric','value'),d)
 empty<-mixedgp_pivot_longer(d[FALSE,],c('a','b'),'metric','value')
 expect_identical(empty,data.frame(id=integer(),metric=character(),value=double()))
 missing<-long[-2L,]
 expect_identical(mixedgp_pivot_wider(missing,'metric','value'),data.frame(id=c(2L,1L),a=c(.2,NA),b=c(NA,.5)))
 expect_error(mixedgp_pivot_wider(rbind(long,long[1L,]),'metric','value'),'unique')
 expect_error(mixedgp_pivot_longer(d,'absent'),'existing')
 multiple<-data.frame(id=c(1L,2L,1L),metric=c('a','b','b'),mean=c(1,2,3),se=c(.1,.2,.3))
 expect_identical(mixedgp_pivot_wider(multiple,'metric',c('mean','se')),
  data.frame(id=c(1L,2L),mean_a=c(1,NA),mean_b=c(3,2),se_a=c(.1,NA),se_b=c(.3,.2)))
})
test_that('calibration crossing sorts and deduplicates without dropping factor levels', {
 d<-data.frame(id=c(2L,1L,2L),method=factor(c('b','a','b'),levels=c('b','a','unused')))
 z<-mixedgp_cross_calibration(d,c(50L,20L,20L))
 expect_identical(z,data.frame(id=c(1L,1L,2L,2L),method=factor(c('a','a','b','b'),levels=c('b','a','unused')),n_calib=c(20L,50L,20L,50L)))
 expect_equal(nrow(mixedgp_cross_calibration(d,integer())),0L)
 expect_error(mixedgp_cross_calibration(z,20L),'already')
})
test_that('fixed block summaries retain finite observations and missing groups', {
 d<-data.frame(block=c('b','a',NA,'b'),rhat=c(1.02,1.03,1.1,Inf),ess=c(10,20,30,Inf))
 z<-summarise_rhat_block(d)
 expect_identical(z$block,c('a','b',NA_character_))
 expect_identical(z$n,rep(1L,3));expect_equal(z$median,c(1.03,1.02,1.1))
 expect_identical(summarise_ess_block(d)$min,c(20,10,30))
 empty<-summarise_rhat_block(d[FALSE,]);expect_equal(nrow(empty),0L)
 expect_identical(names(empty),names(z))
})
test_that('row binding retains empty factor prototypes and zero-column rows', {
 empty<-data.frame(method=factor(character(),levels=c('A','B')))
 actual<-mixedgp_bind_rows(empty,data.frame(method=factor('C')))
 expect_identical(actual$method,factor('C',levels=c('A','B','C')))
 expect_identical(mixedgp_bind_rows(empty)$method,empty$method)
 expect_identical(mixedgp_bind_rows(data.frame(row.names=1:2)),data.frame(row.names=1:2))
 expect_equal(nrow(mixedgp_bind_rows(data.frame(row.names=1:2),data.frame(row.names=1:3))),5L)
 expect_identical(mixedgp_bind_rows(data.frame(row.names=1:2),data.frame(x=3L)),data.frame(x=c(NA_integer_,NA_integer_,3L)))
 expect_identical(mixedgp_bind_rows(data.frame(x=double()),data.frame(x=1L))$x,1)
 expect_identical(mixedgp_bind_rows(data.frame(x=NA),data.frame(x=factor('a',levels=c('a','b'))))$x,
                  factor(c(NA,'a'),levels=c('a','b')))
})
