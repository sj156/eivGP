test_that('LVGP shared dispatch preserves the author optimizer and predictions', {
  skip_if_not_installed('LVGP')
  set.seed(31)
  x<-cbind(runif(24),runif(24),rep(1:4,6));y<-sin(x[,1])+x[,2]+x[,3]/4+rnorm(24,0,.03)
  a<-LVGP::LVGP_fit(x,y,ind_qual=3,n_opt=2,max_iter_ini=4,max_iter_lat=2,eps=c(.1,.01),seed=38,noise=TRUE,parallel=FALSE)
  release<-mixedgp_budget_enter(2);on.exit(release())
  b<-mixedgp_lvgp_fit(x,y,ind_qual=3,n_opt=2,max_iter_ini=4,max_iter_lat=2,eps=c(.1,.01),seed=38,noise=TRUE,parallel=TRUE)
  expect_equal(a$optim_hist,b$optim_hist,tolerance=1e-12)
  expect_equal(LVGP::LVGP_predict(x,a,1),LVGP::LVGP_predict(x,b,1),tolerance=1e-12)
  expect_identical(environment(LVGP::LVGP_fit),asNamespace('LVGP'))
})

test_that('Ocean retries only missing baselines with the original method seeds', {
  folder<-tempfile();dir.create(folder);on.exit(unlink(folder,recursive=TRUE))
  env<-new.env(parent=environment(ocean_initial_functions));ocean_initial_functions(env)
  env$atomic_csv<-ocean_atomic_csv;env$atomic_rds<-ocean_atomic_rds;env$baseline_controls<-ocean_controls()
  env$probability_score<-function(draws,point,y,fold,method,cell)data.frame(fold,method,cell,RMSE=mean((point-y)^2)^.5)
  successes<-c('UC-GP','EzGP');old<-list(draws=setNames(list(matrix(1,2,3),matrix(2,2,3)),successes),means=setNames(list(1:3,2:4),successes),fits=setNames(list(list(token=1),list(token=2)),successes),status=data.frame(method=c('UC-GP','LVGP','EzGP'),status=c('success','unavailable_or_failed','success')))
  saveRDS(old,file.path(folder,'baseline_package_outputs.rds'))
  calls<-list()
  env$run_published_mixedgp_competitors<-function(...,seed,methods,controls) {
    calls[[length(calls)+1L]]<<-list(seed=seed,methods=methods)
    list(draws=setNames(list(matrix(3,2,3)),methods),means=setNames(list(3:5),methods),fits=setNames(list(list(token=3)),methods),status=data.frame(method=methods,status='success'))
  }
  d<-data.frame(G2salinity=1:3,log_pressure=2:4,C=1:3,Y=3:5,cohort_id=1:3)
  env$run_baselines(1,d,d,folder)
  expect_length(calls,1);expect_identical(calls[[1]]$methods,'LVGP')
  expect_equal(calls[[1]]$seed+1,2026092762)
  z<-readRDS(file.path(folder,'baseline_package_outputs.rds'))
  for(n in c('draws','means','fits'))expect_identical(z[[n]][successes],old[[n]][successes])
  expect_true(all(z$status$status=='success'))
  expect_setequal(read.csv(file.path(folder,'baseline_metrics.csv'))$method,c('UC-GP','LVGP','EzGP'))
  env$run_baselines(1,d,d,folder);expect_length(calls,1)
  unlink(file.path(folder,'baseline_metrics.csv'))
  env$run_baselines(1,d,d,folder);expect_length(calls,1)
  expect_true(file.exists(file.path(folder,'baseline_metrics.csv')))
})

test_that('interrupted scoring and failed retries preserve completed methods', {
  folder<-tempfile();dir.create(folder);on.exit(unlink(folder,recursive=TRUE))
  env<-new.env(parent=environment(ocean_initial_functions));ocean_initial_functions(env)
  env$atomic_csv<-ocean_atomic_csv;env$atomic_rds<-ocean_atomic_rds;env$baseline_controls<-ocean_controls()
  env$probability_score<-function(draws,point,y,fold,method,cell)data.frame(fold,method,cell)
  methods<-c('UC-GP','LVGP','EzGP');d<-data.frame(G2salinity=1:3,log_pressure=2:4,C=1:3,Y=3:5,cohort_id=1:3)
  fit<-list(draws=setNames(rep(list(matrix(1,2,3)),3),methods),means=setNames(rep(list(1:3),3),methods),fits=setNames(rep(list(list(token=1)),3),methods),status=data.frame(method=methods,status='success'))
  saveRDS(fit,file.path(folder,'baseline_package_outputs.rds'))
  write.csv(data.frame(method=c('UC-GP','EzGP')),file.path(folder,'baseline_metrics.csv'),row.names=FALSE)
  env$run_published_mixedgp_competitors<-function(...)stop('No refitting allowed')
  env$run_baselines(1,d,d,folder)
  expect_setequal(read.csv(file.path(folder,'baseline_metrics.csv'))$method,methods)
  fit$status$status[2]<-'unavailable_or_failed'
  for(n in c('draws','means','fits'))fit[[n]][['LVGP']]<-NULL
  saveRDS(fit,file.path(folder,'baseline_package_outputs.rds'))
  env$run_published_mixedgp_competitors<-function(...,methods)list(draws=list(),means=list(),fits=list(),status=data.frame(method=methods,status='unavailable_or_failed'))
  expect_error(env$run_baselines(1,d,d,folder),'Baseline failures: LVGP')
  z<-readRDS(file.path(folder,'baseline_package_outputs.rds'))
  expect_false('LVGP'%in%names(z$means));expect_identical(z$fits,fit$fits)
  expect_setequal(read.csv(file.path(folder,'baseline_metrics.csv'))$method,c('UC-GP','EzGP'))
})
