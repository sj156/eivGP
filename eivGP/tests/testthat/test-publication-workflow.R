test_that("publication plans keep paired designs and disjoint batches", {
  f<-mixedgp_publication_workflow
  base<-list(component="publication",output=tempfile(),`data-root`=tempfile())
  capture.output(a<-f("study1",base,tempdir()))
  capture.output(b<-f("study2",modifyList(base,list(stage="full")),tempdir()))
  expect_equal(nrow(a$jobs),48L)
  expect_equal(nrow(b$jobs),500L)
  expect_false(dir.exists(base$output))
  capture.output(x<-f("study2",modifyList(base,list(stage="full",reps="1:25")),tempdir()))
  capture.output(y<-f("study2",modifyList(base,list(stage="full",reps="26:50")),tempdir()))
  expect_length(intersect(x$jobs$rep,y$jobs$rep),0)
  expect_false(identical(x$commands$reference$output,y$commands$reference$output))
  capture.output(z<-f("study2",modifyList(base,list(stage="integration")),tempdir()))
  expect_equal(z$commands$outer_doubled$outer,"64")
  expect_equal(z$commands$latent_doubled$latent,"256")
  expect_equal(z$commands$gp_states_doubled[["inner-draws"]],"8")
  expect_error(f("study2",modifyList(base,list(action="run")),tempdir()),"full-fit-map")
  expect_error(f("study2",modifyList(base,list(reps="1,1")),tempdir()),"distinct")
  expect_error(f("study1",modifyList(base,list(`full-fit-map`="x")),tempdir()),"Study I")
})

test_that("follow-up entrypoint selects only the missing completion grid", {
  capture.output(a <- run_paper_study("study1", list(component="follow-up", action="plan", profile="paper")))
  capture.output(b <- run_paper_study("study2", list(component="follow-up", action="plan", profile="paper")))
  expect_equal(nrow(a$jobs), 600L)
  expect_equal(nrow(b$jobs), 500L)
  expect_true(all(grepl("-CC$", a$jobs$method)))
  expect_equal(sum(b$jobs$method == "FULL"), 100L)
  expect_false(any(b$jobs$method %in% c("UC-GP", "LVGP", "EzGP")))
})
