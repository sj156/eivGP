repo<-Sys.getenv('EIVGP_TEST_REPO');stopifnot(nzchar(repo))
for(application in c('adni','oai'))local({
  app<-application
  e<-new.env(parent=globalenv());sys.source(file.path(repo,'tools',paste0(app,'-tools.R')),e)
  api<-get(paste0(app,'_load_api'),e)(repo)
  collect<-get(paste0(app,'_screen_collect'),api)
  path<-get(paste0(app,'_path'),api)
  testthat::test_that(paste(app,'method summaries ignore unfinished opponent tables'),{
    root<-tempfile();dir.create(root);on.exit(unlink(root,recursive=TRUE))
    output<-file.path(root,'case');dir.create(output)
    dir<-file.path(output,'S40/analysis/fold01/O50');dir.create(dir,recursive=TRUE)
    writeLines('{}',file.path(dir,'EVALUATION_VALIDATION.json'))
    ev<-data.frame(fold=1L,stage='S40',cell='O50',method='EIV-GP',protocol='OI',RMSE_SD=.5)
    base<-data.frame(fold=1L,stage='BASELINE',cell='OI',method='UC-GP',protocol='OI',RMSE_SD=.7)
    ep<-file.path(dir,'prediction_metrics.csv')
    bp<-file.path(output,'baselines/fold01/UC-GP/metrics.csv');dir.create(dirname(bp),recursive=TRUE)
    write.csv(ev,ep,row.names=FALSE);writeLines(c('a,b','1,2,3','4,5,6,7'),bp)
    m<-list(cases=list(list(id='synthetic',output=output)),output_root=root,stages=40L,trial_id='synthetic')
    testthat::expect_error(collect(m,api,'eivGP'),NA)
    saved<-file.path(root,'reports/eivGP/progress/fivefold_prediction.csv')
    hash<-tools::md5sum(saved)
    write.csv(base,bp,row.names=FALSE);writeLines(c('a,b','1,2,3','4,5,6,7'),ep)
    testthat::expect_error(collect(m,api,'competitors'),NA)
    testthat::expect_identical(tools::md5sum(saved),hash)
    own<-read.csv(file.path(root,'reports/competitors/progress/fivefold_prediction.csv'))
    testthat::expect_identical(own$method,'UC-GP')
    write.csv(ev,ep,row.names=FALSE)
    combined<-collect(m,api,'report')
    testthat::expect_setequal(combined$prediction$method,c('EIV-GP','UC-GP'))
  })
})
